import chalk from 'chalk';

// הדפסת הודעה פשוטה בצבע
console.log(chalk.blue('Hello! This is a blue message.'));

// שילוב של צבע והדגשה (Bold)
console.log(chalk.green.bold('And this is a green, bold message!'));

// צבע טקסט יחד עם צבע רקע
console.log(chalk.red.bgWhite('Red text on a white background.'));
